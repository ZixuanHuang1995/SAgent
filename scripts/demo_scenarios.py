    # 設計審查後才新增的階段（名稱、說明），變更需求放在這裡
    late_phase: tuple[str, str] | None = None
    # 建立了但還沒有任何版本的 Spec（階段、標題、文件類型）
    pending: tuple[str, str, str] | None = None
    # 資料庫設計的手動編輯：class 插入類別圖、temp_restore 加暫存欄位再還原、none 不改
    db_edit: str = "none"
