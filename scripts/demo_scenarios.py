from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Scenario:
    name: str
    code: str
    description: str
    # 依順序的階段（名稱、說明）
    phases: list[tuple[str, str]]
    # 各份 Spec 的標題，key：idea、feature、architecture、database、change、glossary、legacy（主打專案另有 test_plan）
