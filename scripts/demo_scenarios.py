    revise_target: str
    # 只有範本骨架、還沒寫的 Spec（標題、文件類型）
    skeleton: tuple[str, str]
    # 基準版本之後，名詞表手動補的一列
    glossary_row: str
    # 依文件類型覆寫 AI 選項，例如 {"database": {"max_revisions": 0}}
    options: dict[str, dict] = field(default_factory=dict)
    # 只收需求萃取階段的基準版本（名稱、說明）
